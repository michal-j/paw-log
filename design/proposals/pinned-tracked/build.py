#!/usr/bin/env python3
"""Assemble pinned-tracked-prototype.html (opens straight from disk) and copy-proposal.csv.

Inlines the app's own CSS (src/styles/tokens.css is generated by `npm run generate`), the Timeline and
Day view markup captured from the running demo (src/captured/, EN and PL), the strings and the prototype
script. Run from anywhere: python3 design/proposals/pinned-tracked/build.py
"""
import csv
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[2]
SRC = HERE / "src"

APP_CSS = [
    "src/styles/tokens.css",
    "src/styles/global.css",
    "src/components/controls.css",
    "src/components/marks.css",
    "src/day/day.css",
    "src/timeline/timeline.css",
]
DAYS = ["03", "10", "12", "14", "15"]

FLOWS = [
    ("Timeline (unchanged geometry)", "screen=timeline"),
    ("Pinned notes", "screen=pinned"),
    ("Pinned: reorder", "screen=pinned&reorder=1"),
    ("Pinned: edit a note", "screen=pinned&sheet=pin:n2"),
    ("Tracked list", "screen=tracked"),
    ("Condition: Lump A", "screen=cond:c1"),
    ("Condition: Stomach trouble", "screen=cond:c2"),
    ("Condition: resolved (Reflux)", "screen=cond:c4"),
    ("Edit condition", "screen=cond:c1&sheet=cond:c1"),
    ("Mark as resolved", "screen=cond:c2&sheet=resolve:c2"),
    ("Photo viewer (swipe)", "screen=cond:c1&viewer=cond:c1@1"),
    ("Compare first and latest", "screen=cond:c1&compare=c1"),
    ("Add from a condition", "screen=cond:c1&sheet=add"),
    ("+ Add (Photo added)", "screen=day:2026-10-15&sheet=add"),
    ("Photo: iPhone menu", "screen=cond:c1&sheet=photo-new:c1&ios=1"),
    ("Photo: picked, link to conditions", "screen=cond:c1&sheet=photo-new:c1&picked=2"),
    ("Day 14 Oct: linked events", "screen=day:2026-10-14"),
    ("Day 10 Oct: photo card", "screen=day:2026-10-10"),
    ("Event sheet: link conditions", "screen=day:2026-10-14&sheet=event:e1014m"),
    ("Empty: Pinned", "screen=pinned&empty=1"),
    ("Empty: Tracked", "screen=tracked&empty=1"),
]


def split_day(html: str) -> dict:
    head = html[html.index('<div class="day__top">'): html.index('<div class="day__body">')]
    parts = html[html.index('<div class="day__section">'): html.rindex("</div></section>")]
    return {"head": head, "parts": parts}


def main() -> None:
    css = "\n".join((REPO / p).read_text(encoding="utf-8") for p in APP_CSS)
    css += "\n" + (SRC / "proto.css").read_text(encoding="utf-8")
    cap = {}
    for lang in ("en", "pl"):
        cap[lang] = {
            "timeline": (SRC / "captured" / f"timeline-{lang}.html").read_text(encoding="utf-8"),
            "days": {f"2026-10-{d}": split_day((SRC / "captured" / f"day-{d}-{lang}.html").read_text(encoding="utf-8")) for d in DAYS},
        }
    strings = json.loads((SRC / "strings.json").read_text(encoding="utf-8"))
    js = "const STRINGS = " + json.dumps(strings, ensure_ascii=False) + ";\n"
    js += "const CAP = " + json.dumps(cap, ensure_ascii=False) + ";\n"
    js += (SRC / "photos.js").read_text(encoding="utf-8") + "\n" + (SRC / "proto.js").read_text(encoding="utf-8")
    js = js.replace("</script", "<\\/script")
    flows = "".join(
        f'<li><a class="menu-row" href="#{q}"><span class="menu-row__text">{label}</span></a></li>' for label, q in FLOWS
    )
    page = f"""<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<title>PawLog: Pinned and Tracked</title>
<style>
{css}
</style>
</head>
<body>
<div class="proto">
  <main class="app" id="app"></main>
  <aside class="flows" aria-label="Flows">
    <h2 class="flows__title">Flows</h2>
    <p class="flows__note">Proposal, not built. Fictional data, today is Thu 15 Oct. Changes reset on reload.</p>
    <div class="lang"><button type="button" class="lang-btn" data-flang="en">EN</button><button type="button" class="lang-btn" data-flang="pl">PL</button></div>
    <ul class="flows__list">{flows}</ul>
  </aside>
</div>
<script>
{js}
</script>
</body>
</html>
"""
    (HERE / "pinned-tracked-prototype.html").write_text(page, encoding="utf-8")

    with open(HERE / "copy-proposal.csv", "w", newline="", encoding="utf-8-sig") as fh:
        w = csv.writer(fh)
        w.writerow(["#", "Where (code name)", "English", "Polish", "EN chars", "PL chars", "Fit note", "Your notes"])
        for s in strings:
            if "id" not in s:
                continue
            fit = "PL >20% longer; fits at 390 (checked)" if len(s["pl"]) > len(s["en"]) * 1.2 and len(s["pl"]) - len(s["en"]) > 3 else ""
            w.writerow([s["id"], s["key"], s["en"], s["pl"], len(s["en"]), len(s["pl"]), fit, "DRAFT pending CEO review; " + s["note"]])
    print("built", (HERE / "pinned-tracked-prototype.html").stat().st_size, "bytes;", sum(1 for s in strings if "id" in s), "new strings")


if __name__ == "__main__":
    main()
