// Pure helpers behind `npm run generate`; imported by the script and by unit tests.

/** Parse RFC 4180 CSV (quoted fields, doubled quotes, embedded newlines, optional BOM). */
export function parseCsv(text) {
  const rows = [];
  let row = [];
  let field = '';
  let quoted = false;
  const src = text.replace(/^\uFEFF/, '');
  for (let i = 0; i < src.length; i++) {
    const ch = src[i];
    if (quoted) {
      if (ch === '"' && src[i + 1] === '"') {
        field += '"';
        i++;
      } else if (ch === '"') {
        quoted = false;
      } else {
        field += ch;
      }
    } else if (ch === '"') {
      quoted = true;
    } else if (ch === ',') {
      row.push(field);
      field = '';
    } else if (ch === '\n' || ch === '\r') {
      if (ch === '\r' && src[i + 1] === '\n') i++;
      row.push(field);
      field = '';
      if (row.some((cell) => cell !== '')) rows.push(row);
      row = [];
    } else {
      field += ch;
    }
  }
  row.push(field);
  if (row.some((cell) => cell !== '')) rows.push(row);
  return rows;
}

/**
 * Build the EN and PL catalogues from the copy CSV.
 * The "Where (code name)" column is not unique (groups such as `meal`, `dose`, empty cells),
 * so a code is used as the key only when it appears once; otherwise the key is `<code|copy>.<row #>`.
 */
export function buildCatalogues(csvText) {
  const [header, ...rows] = parseCsv(csvText);
  const col = (name) => header.findIndex((h) => h.trim() === name);
  const iNum = col('#');
  const iCode = col('Where (code name)');
  const iEn = col('English');
  const iPl = col('Polish');
  if ([iNum, iCode, iEn, iPl].some((i) => i < 0)) throw new Error('Copy CSV header not recognised');
  const counts = new Map();
  for (const r of rows) counts.set(r[iCode], (counts.get(r[iCode]) ?? 0) + 1);
  const en = {};
  const pl = {};
  for (const r of rows) {
    const code = r[iCode];
    const key = code && counts.get(code) === 1 ? code : `${code || 'copy'}.${r[iNum]}`;
    if (key in en) throw new Error(`Duplicate catalogue key ${key}`);
    en[key] = r[iEn];
    pl[key] = r[iPl];
  }
  return { en, pl };
}

const group = (tokens, prefix = '') =>
  tokens.map((t) => `  --${prefix}${t.name}: ${t.value};`).join('\n');

/** Turn docs/design-system/tokens.json into a :root block of CSS variables. */
export function buildTokensCss(tokens) {
  const parts = [
    '/* Generated by scripts/generate.mjs from docs/design-system/tokens.json. Do not edit. */',
    ':root {',
    group(tokens.color.tokens, 'color-'),
    group(tokens.spacing.tokens),
    group(tokens.radius.tokens),
    group(tokens.shadow.tokens),
    `  --font-sans: ${tokens.type.families.sans};`,
    `  --font-display: ${tokens.type.families.display};`,
  ];
  for (const g of tokens.type.groups) {
    for (const s of g.styles) {
      parts.push(`  --type-${s.name}-family: var(--font-${g.family});`);
      parts.push(`  --type-${s.name}-size: ${s.fontSize};`);
      parts.push(`  --type-${s.name}-line: ${s.lineHeight};`);
      parts.push(`  --type-${s.name}-weight: ${s.fontWeight};`);
      if (s.letterSpacing) parts.push(`  --type-${s.name}-tracking: ${s.letterSpacing};`);
    }
  }
  parts.push('}', '');
  return parts.join('\n');
}
